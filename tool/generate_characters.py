#!/usr/bin/env python3
"""Generates pixel-art character part sprites as PNG files (assets/characters).

Each character part is rendered on a 16x16 transparent canvas so that all parts
stack perfectly when composited by CharacterPreview. Tokens:
  . transparent   1 -> color1   2 -> color2   k -> outline   w -> white   r -> red
"""

import os
from PIL import Image

CANVAS_W = 16
CANVAS_H = 16
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "characters")


def _rgb(v):
    return ((v >> 16) & 0xFF, (v >> 8) & 0xFF, v & 0xFF, 255)


COLOR = {
    "k": _rgb(0xFF1A1A2E),
    "w": (255, 255, 255, 255),
    "r": _rgb(0xFFE74C3C),
}


def render(part_id, rows, c1, c2, yo=0):
    img = Image.new("RGBA", (CANVAS_W, CANVAS_H), (0, 0, 0, 0))
    px = img.load()
    color1 = _rgb(c1) if c1 else None
    color2 = _rgb(c2) if c2 else None
    for r, line in enumerate(rows):
        y = yo + r
        if y < 0 or y >= CANVAS_H:
            continue
        for x, ch in enumerate(line):
            if x >= CANVAS_W:
                break
            if ch == ".":
                continue
            if ch == "1" and color1:
                px[x, y] = color1
            elif ch == "2" and color2:
                px[x, y] = color2
            elif ch in COLOR:
                px[x, y] = COLOR[ch]
    os.makedirs(OUT, exist_ok=True)
    img.save(os.path.join(OUT, part_id + ".png"))


